// Copies Copas ABIs (../abis) and deployments (../contracts/deployments/<chainId>.json)
// into lib/copas/generated so the web build never imports outside its root.
// Runs before dev/build; missing sources keep the last generated copy (or empty fallback).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = "lib/copas/generated";
mkdirSync(out, { recursive: true });
const abis = {};
const abiDir = "../abis";
if (existsSync(abiDir))
  for (const f of readdirSync(abiDir).filter((f) => f.endsWith(".json") && f !== "PerplExchange.json")) {
    const j = JSON.parse(readFileSync(join(abiDir, f), "utf8"));
    abis[f.replace(".json", "")] = Array.isArray(j) ? j : j.abi;
  }
const deployments = {};
const depDir = "../contracts/deployments";
if (existsSync(depDir))
  for (const f of readdirSync(depDir).filter((f) => /^\d+\.json$/.test(f))) deployments[f.replace(".json", "")] = JSON.parse(readFileSync(join(depDir, f), "utf8"));

const write = (name, obj, type) => {
  if (!Object.keys(obj).length && existsSync(join(out, name))) return console.log(`sync-contracts: kept existing ${name}`);
  writeFileSync(join(out, name), `// Generated by scripts/sync-contracts.mjs. Do not edit.\nexport const data = ${JSON.stringify(obj, null, 1)} as const;\nexport type T = ${type};\n`);
};
write("abis.ts", abis, "typeof data");
write("deployments.ts", deployments, "Record<string, Deployment>;\ntype Deployment = { registry?: `0x${string}`; breachMarket?: `0x${string}`; agentRegistry?: `0x${string}`; exchange?: `0x${string}`; ausd?: `0x${string}`; identity8004?: `0x${string}`; block?: number }");
console.log(`sync-contracts: ${Object.keys(abis).length} abis, deployments for [${Object.keys(deployments)}]`);
